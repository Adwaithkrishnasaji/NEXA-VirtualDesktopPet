const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('nexaApi', {
  readPetSetup: () => ipcRenderer.invoke('setup:read'),
  savePetSetup: (setup) => ipcRenderer.invoke('setup:save', setup),
  readClipboardText: () => ipcRenderer.invoke('clipboard:read-text'),
  readMaintenanceProfile: () => ipcRenderer.invoke('maintenance:read'),
  saveMaintenanceProfile: (profile) => ipcRenderer.invoke('maintenance:save-profile', profile),
  openMaintenance: () => ipcRenderer.invoke('maintenance:open'),
  getCredentialStatus: () => ipcRenderer.invoke('credentials:status'),
  updateCredentials: (credentials) => ipcRenderer.invoke('credentials:update', credentials),
  listPersonalMemories: () => ipcRenderer.invoke('memory:list'),
  deletePersonalMemory: (id) => ipcRenderer.invoke('memory:delete', id),
  clearPersonalMemories: () => ipcRenderer.invoke('memory:clear'),
  launchApp: (appName) => ipcRenderer.invoke('local:launch-app', appName),
  playSpotifyMusic: (song) => ipcRenderer.invoke('local:play-spotify-music', song),
  closeApp: (appName) => ipcRenderer.invoke('local:close-app', appName),
  sendWhatsAppMessage: (recipient, message, userPrompt, history) => ipcRenderer.invoke('whatsapp:send-message', recipient, message, userPrompt, history),
  setChatHeight: (height) => ipcRenderer.invoke('pet:set-chat-height', height),
  restartPet: () => ipcRenderer.invoke('pet:restart'),
  resetWindowPosition: () => ipcRenderer.invoke('pet:reset-position'),
  setPosition: (x, y) => ipcRenderer.invoke('pet:set-position', x, y),
  setPositionLocked: (locked) => ipcRenderer.send('pet:set-position-locked', locked),
  setMouseInteractive: (interactive) => ipcRenderer.send('pet:set-interactive', interactive),
  startWindowDrag: (screenX, screenY) => ipcRenderer.send('pet:drag-start', screenX, screenY),
  endWindowDrag: () => ipcRenderer.send('pet:drag-end'),
  showContextMenu: () => ipcRenderer.send('pet:context-menu'),
  requestAI: (prompt, history, requestId, images, seriousMode) => ipcRenderer.invoke('ai:chat', prompt, history, requestId, images, seriousMode),
  generateImage: (prompt) => ipcRenderer.invoke('ai:generate-image', prompt),
  speakText: (text) => ipcRenderer.invoke('speech:synthesize', text),
  listCaptureSources: () => ipcRenderer.invoke('capture:list-sources'),
  captureScreen: (sourceId) => ipcRenderer.invoke('capture:screen', sourceId),
  onAIStream: (callback) => ipcRenderer.on('ai:chat-stream', (_event, payload) => callback(payload)),
  onPetControlRequest: (callback) => ipcRenderer.on('pet:control-request', (_event, payload) => callback(payload)),
  reportPetControlResult: (requestId, error, result) => ipcRenderer.send('pet:control-result', requestId, error, result),
  onClearChat: (callback) => ipcRenderer.on('chat:clear', callback),
  scheduleReminder: (message, dateTime, type) => ipcRenderer.invoke('reminder:schedule', message, dateTime, type),
  parseTimerIntent: (text) => ipcRenderer.invoke('timer:parse-intent', text),
  onReminderDue: (callback) => ipcRenderer.on('reminder:due', (_event, reminder) => callback(reminder)),
});
